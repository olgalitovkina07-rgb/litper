package ru.litper.structure;

/**
 * Извлекает ключ (строку) из значения, которое кладётся в {@link Trie}.
 *
 * <p>Вынесено отдельно, чтобы структура данных не зависела от модели предметной области:
 * для контактов ключ — имя, для других сущностей ключ может быть любым.</p>
 *
 * @param <T> тип хранимого значения
 */
@FunctionalInterface
public interface KeyExtractor<T> {

    /**
     * @param value хранимое значение (не {@code null})
     * @return ключ, по которому значение попадёт в дерево
     */
    String key(T value);
}